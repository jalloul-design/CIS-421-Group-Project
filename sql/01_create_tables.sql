--======================================================================
-- 01_create_tables.sql
-- Cedar Table Kitchen database - create all tables
-- Written By: Nour
--
-- Column names follow section 2.5 of the requirements doc (same names
-- Mira's Q1-Q4 use). Update to match Moe's final schema if anything changes.
--
-- ID columns are identity columns that start at 1001. The sample data in
-- 02_insert_data.sql uses small IDs (1, 2, 3, ...) so it is easy to read,
-- and any new row inserted later gets 1001, 1002, ... with no collisions.
--
-- Constraint names: pk_ = primary key, fk_ = foreign key,
-- uq_ = unique, ck_ = check. Named constraints make error messages readable.
--======================================================================


-- EMPLOYEE: recursive 1:N (an employee's manager is another employee)
CREATE TABLE employee (
    employee_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    first_name    VARCHAR2(30)  NOT NULL,
    last_name     VARCHAR2(30)  NOT NULL,
    role          VARCHAR2(30)  NOT NULL,
    hourly_rate   NUMBER(6,2)   NOT NULL,
    hire_date     DATE          NOT NULL,
    manager_id    NUMBER,
    CONSTRAINT pk_employee        PRIMARY KEY (employee_id),
    CONSTRAINT fk_employee_mgr    FOREIGN KEY (manager_id) REFERENCES employee (employee_id),
    CONSTRAINT ck_employee_rate   CHECK (hourly_rate > 0)
);

-- SHIFT: each shift belongs to exactly one employee
CREATE TABLE shift (
    shift_id          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    employee_id       NUMBER  NOT NULL,
    shift_start_time  DATE    NOT NULL,
    shift_end_time    DATE    NOT NULL,
    CONSTRAINT pk_shift        PRIMARY KEY (shift_id),
    CONSTRAINT fk_shift_emp    FOREIGN KEY (employee_id) REFERENCES employee (employee_id),
    CONSTRAINT ck_shift_times  CHECK (shift_end_time > shift_start_time)
);

CREATE TABLE menu_category (
    category_id  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    name         VARCHAR2(30)  NOT NULL,
    CONSTRAINT pk_menu_category  PRIMARY KEY (category_id),
    CONSTRAINT uq_category_name  UNIQUE (name)
);

-- MENU_ITEM: is_active = 'N' means the item is off the menu (Q12 blocks it)
CREATE TABLE menu_item (
    item_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    category_id  NUMBER        NOT NULL,
    name         VARCHAR2(50)  NOT NULL,
    price        NUMBER(6,2)   NOT NULL,
    is_active    CHAR(1)       DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_menu_item        PRIMARY KEY (item_id),
    CONSTRAINT fk_menu_item_cat    FOREIGN KEY (category_id) REFERENCES menu_category (category_id),
    CONSTRAINT uq_menu_item_name   UNIQUE (name),
    CONSTRAINT ck_menu_item_price  CHECK (price > 0),
    CONSTRAINT ck_menu_item_active CHECK (is_active IN ('Y', 'N'))
);

CREATE TABLE customer (
    customer_id  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    name         VARCHAR2(60)  NOT NULL,
    phone        VARCHAR2(15)  NOT NULL,
    email        VARCHAR2(80),
    CONSTRAINT pk_customer        PRIMARY KEY (customer_id),
    CONSTRAINT uq_customer_phone  UNIQUE (phone)
);

-- DELIVERY_PLATFORM: commission_rate 0.25 = 25%
CREATE TABLE delivery_platform (
    delivery_platform_id  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    name                  VARCHAR2(30)  NOT NULL,
    commission_rate       NUMBER(4,3)   NOT NULL,
    CONSTRAINT pk_delivery_platform  PRIMARY KEY (delivery_platform_id),
    CONSTRAINT uq_platform_name      UNIQUE (name),
    CONSTRAINT ck_platform_rate      CHECK (commission_rate BETWEEN 0 AND 1)
);

-- ORDERS: customer_id is optional (walk-in dine-in orders).
-- ck_orders_platform enforces "a delivery order must have a platform;
-- other orders must not".
CREATE TABLE orders (
    order_id              NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    customer_id           NUMBER,
    employee_id           NUMBER        NOT NULL,
    delivery_platform_id  NUMBER,
    order_time            DATE          NOT NULL,
    order_type            VARCHAR2(10)  NOT NULL,
    status                VARCHAR2(10)  DEFAULT 'PLACED' NOT NULL,
    CONSTRAINT pk_orders           PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_customer  FOREIGN KEY (customer_id) REFERENCES customer (customer_id),
    CONSTRAINT fk_orders_emp       FOREIGN KEY (employee_id) REFERENCES employee (employee_id),
    CONSTRAINT fk_orders_platform  FOREIGN KEY (delivery_platform_id)
                                   REFERENCES delivery_platform (delivery_platform_id),
    CONSTRAINT ck_orders_type      CHECK (order_type IN ('DINE_IN', 'TAKEOUT', 'DELIVERY')),
    CONSTRAINT ck_orders_status    CHECK (status IN ('PLACED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_orders_platform  CHECK (
        (order_type = 'DELIVERY'  AND delivery_platform_id IS NOT NULL) OR
        (order_type <> 'DELIVERY' AND delivery_platform_id IS NULL)
    )
);

-- ORDER_ITEM: weak entity, identified by its order + the menu item.
-- ON DELETE CASCADE: deleting an order deletes its lines (used by Q10).
-- unit_price is the price at the time of the order (filled by the Q12 trigger).
CREATE TABLE order_item (
    order_id    NUMBER       NOT NULL,
    item_id     NUMBER       NOT NULL,
    quantity    NUMBER(3)    NOT NULL,
    unit_price  NUMBER(6,2)  NOT NULL,
    CONSTRAINT pk_order_item        PRIMARY KEY (order_id, item_id),
    CONSTRAINT fk_order_item_order  FOREIGN KEY (order_id) REFERENCES orders (order_id)
                                    ON DELETE CASCADE,
    CONSTRAINT fk_order_item_item   FOREIGN KEY (item_id) REFERENCES menu_item (item_id),
    CONSTRAINT ck_order_item_qty    CHECK (quantity > 0),
    CONSTRAINT ck_order_item_price  CHECK (unit_price > 0)
);

CREATE TABLE supplier (
    supplier_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    name          VARCHAR2(60)  NOT NULL,
    phone_number  VARCHAR2(15)  NOT NULL,
    CONSTRAINT pk_supplier       PRIMARY KEY (supplier_id),
    CONSTRAINT uq_supplier_name  UNIQUE (name)
);

-- INVENTORY: reorder when quantity_left <= reorder_threshold (Q4).
-- quantity_left can't go negative, so Q11 can't use more stock than exists.
CREATE TABLE inventory (
    inventory_id       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
    supplier_id        NUMBER        NOT NULL,
    item_name          VARCHAR2(50)  NOT NULL,
    unit               VARCHAR2(10)  NOT NULL,
    quantity_left      NUMBER(8,2)   NOT NULL,
    reorder_threshold  NUMBER(8,2)   NOT NULL,
    CONSTRAINT pk_inventory            PRIMARY KEY (inventory_id),
    CONSTRAINT fk_inventory_supplier   FOREIGN KEY (supplier_id) REFERENCES supplier (supplier_id),
    CONSTRAINT uq_inventory_name       UNIQUE (item_name),
    CONSTRAINT ck_inventory_qty        CHECK (quantity_left >= 0),
    CONSTRAINT ck_inventory_threshold  CHECK (reorder_threshold >= 0)
);

-- RECIPE: M:N between MENU_ITEM and INVENTORY.
-- qty_needed = amount of the ingredient for ONE serving, in INVENTORY.unit.
CREATE TABLE recipe (
    item_id       NUMBER       NOT NULL,
    inventory_id  NUMBER       NOT NULL,
    qty_needed    NUMBER(6,2)  NOT NULL,
    CONSTRAINT pk_recipe            PRIMARY KEY (item_id, inventory_id),
    CONSTRAINT fk_recipe_item       FOREIGN KEY (item_id) REFERENCES menu_item (item_id),
    CONSTRAINT fk_recipe_inventory  FOREIGN KEY (inventory_id) REFERENCES inventory (inventory_id),
    CONSTRAINT ck_recipe_qty        CHECK (qty_needed > 0)
);
